// Package push delivers notifications to registered devices behind one
// transport interface. Every request leaves Earnest through internal/outbound,
// so the shared address checks and host spacing apply to all transports.
//
// Agent text is untrusted because it originates from feed content an agent
// read. It reaches a payload only when the device opted in and the transport
// either encrypts it end to end or is operated by you; see Device.TextAllowed.
package push

import (
	"context"
	"errors"
	"fmt"
	"slices"

	"github.com/L-K-M/Earnest/internal/outbound"
)

// Kind names one push transport.
type Kind string

const (
	KindNtfy        Kind = "ntfy"
	KindWebPush     Kind = "webpush"
	KindUnifiedPush Kind = "unifiedpush"
	KindAPNs        Kind = "apns"
)

// Category is a closed, server-defined notification category. Agents cannot
// mint categories, so a hostile agent cannot raise its own importance.
type Category string

const (
	// CategoryAlert marks a notification the user asked to be told about.
	CategoryAlert Category = "alert"
)

// Device is one registered push destination. Only the fields matching
// Device.Kind are used.
type Device struct {
	Kind Kind
	// Endpoint is the transport destination: an ntfy publish URL, a Web Push
	// or UnifiedPush subscription URL, or an APNs device token.
	Endpoint string
	// ShowText opts this device into receiving agent text on transports that
	// can protect it. It never enables agent text on APNs or a third-party
	// ntfy server.
	ShowText bool

	// ntfy credentials. Token is a bearer token; Username and Password select
	// HTTP basic authentication instead. SelfHosted records that you operate
	// the ntfy server, which is what permits agent text on this plaintext
	// path.
	Token      string
	Username   string
	Password   string
	SelfHosted bool

	// Web Push and UnifiedPush subscription keys, base64url-encoded without
	// padding.
	P256DH     string
	AuthSecret string
}

// TextAllowed reports whether the agent's own words may travel to this
// device.
//
// Agent text is written by an agent that read attacker-controlled feed
// content, so llm.md invariant 3 keeps it inside the tailnet by default. Two
// properties justify an exception:
//
//   - Web Push and UnifiedPush encrypt the payload end to end with RFC 8291,
//     so only the device's browser or app can read it;
//   - a self-hosted ntfy server is one you operate, so its operator is not a
//     third party.
//
// APNs and third-party ntfy hand payloads to the provider in the clear, so
// they never carry agent text, even when ShowText is set.
func (d Device) TextAllowed() bool {
	switch d.Kind {
	case KindWebPush, KindUnifiedPush:
		return d.ShowText
	case KindNtfy:
		return d.ShowText && d.SelfHosted
	default:
		return false
	}
}

// Message is a notification ready to send. Title and Body are generated by
// Earnest and never come from an agent, and neither carries a URL: tapping
// opens the entry inside Earnest and clients fetch the rest over the tailnet.
type Message struct {
	Title string
	Body  string
	// NotificationID identifies the stored notification so a client can fetch
	// it after the user opens the push.
	NotificationID string
	Category       Category
	// AgentText is the agent's own words, if any. Transports include it only
	// when Device.TextAllowed reports true.
	AgentText string
}

// Receipt records what a transport learned about an accepted message.
type Receipt struct {
	// ProviderID identifies the message at the provider: the APNs "apns-id"
	// header, the ntfy message ID, or the Web Push Location header. Empty
	// when the provider did not supply one.
	ProviderID string
}

// Transport delivers one message to one device. Implementations are safe for
// concurrent use.
type Transport interface {
	Send(ctx context.Context, device Device, message Message) (Receipt, error)
}

// Config configures the transports that send through the shared outbound
// client.
type Config struct {
	// Client is Earnest's single egress client. Every push request goes
	// through it, so address checks and host spacing apply.
	Client *outbound.Client

	// ExtraPorts lists destination ports beyond 80 and 443 that push
	// endpoints may use, such as a self-hosted ntfy server or a tailnet
	// UnifiedPush relay. The outbound client rejects every other port.
	ExtraPorts []uint16
}

// egress builds the request policy for a transport. unregisteredOnGone
// selects whether 404 and 410 mark the device as unregistered.
func (c Config) egress(unregisteredOnGone bool) egress {
	return egress{client: c.Client, extraPorts: c.ExtraPorts, unregisteredOnGone: unregisteredOnGone}
}

// ErrUnknownTransport is returned when no transport is registered for a kind.
var ErrUnknownTransport = errors.New("unknown push transport")

// Registry maps transport kinds to their implementations. Register is for
// setup; Get and Kinds assume the registry is no longer being mutated.
type Registry struct {
	transports map[Kind]Transport
}

// NewRegistry returns an empty registry.
func NewRegistry() *Registry {
	return &Registry{transports: make(map[Kind]Transport)}
}

// Register adds t under kind. An empty kind or nil transport is rejected.
func (r *Registry) Register(kind Kind, t Transport) error {
	if kind == "" {
		return fmt.Errorf("%w: empty kind", ErrUnknownTransport)
	}
	if t == nil {
		return fmt.Errorf("%w: nil transport", ErrUnknownTransport)
	}
	r.transports[kind] = t
	return nil
}

// Get returns the transport registered for kind.
func (r *Registry) Get(kind Kind) (Transport, error) {
	t, ok := r.transports[kind]
	if !ok {
		return nil, fmt.Errorf("%w: %s", ErrUnknownTransport, kind)
	}
	return t, nil
}

// Kinds returns the registered kinds in sorted order.
func (r *Registry) Kinds() []Kind {
	kinds := make([]Kind, 0, len(r.transports))
	for kind := range r.transports {
		kinds = append(kinds, kind)
	}
	slices.Sort(kinds)
	return kinds
}
