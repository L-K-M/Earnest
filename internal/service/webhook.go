// WebhookEventType is the closed set of events a webhook can subscribe to.
type WebhookEventType string

const (
	WebhookFeedFailing  WebhookEventType = "feed.failing"
	WebhookEditionReady WebhookEventType = "edition.ready"
	WebhookEntryMatched WebhookEventType = "entry.matched"
)

// WebhookEvent is one emitted domain occurrence bound for webhook delivery.
// Payloads carry only IDs: the receiver fetches content over the tailnet.
type WebhookEvent struct {
	Type      WebhookEventType
	FeedID    int64
	EntryID   int64
	EditionID int64
}

// validate enforces the closed event set and each event's exact ID set.
func (ev WebhookEvent) validate() error {
	ok := false
	switch ev.Type {
	case WebhookFeedFailing:
		ok = ev.FeedID > 0 && ev.EntryID == 0 && ev.EditionID == 0
	case WebhookEditionReady:
		ok = ev.FeedID == 0 && ev.EntryID == 0 && ev.EditionID > 0
	case WebhookEntryMatched:
		ok = ev.FeedID > 0 && ev.EntryID > 0 && ev.EditionID == 0
	}
	if !ok {
		return fmt.Errorf("webhook event %q ids: %w", ev.Type, ErrInvalid)
	}
	return nil
}

// dedupeKey identifies the logical event for pending-job deduplication.
func (ev WebhookEvent) dedupeKey() string {
	return fmt.Sprintf("%s:f%d:e%d:ed%d", ev.Type, ev.FeedID, ev.EntryID, ev.EditionID)
}

// body serialises the Standard Webhooks message: type, creation time and a
// data object that contains only the relevant feed/entry/edition IDs.
func (ev WebhookEvent) body(at time.Time) (string, error) {
	data := map[string]int64{}
	switch ev.Type {
	case WebhookFeedFailing:
		data["feed_id"] = ev.FeedID
	case WebhookEditionReady:
		data["edition_id"] = ev.EditionID
	case WebhookEntryMatched:
		data["feed_id"] = ev.FeedID
		data["entry_id"] = ev.EntryID
	}
	body, err := json.Marshal(map[string]any{
		"type":      string(ev.Type),
		"timestamp": at.UTC().Format(time.RFC3339),
		"data":      data,
	})
	if err != nil {
		return "", fmt.Errorf("encode webhook event: %w", err)
	}
	return string(body), nil
}

// Webhook is a user-owned Standard Webhooks destination. The signing secret
// is shown once at creation and is never present here.
type Webhook struct {
	ID                  int64     `json:"id"`
	URL                 string    `json:"url"`
	Events              []string  `json:"events"`
	Active              bool      `json:"active"`
	ConsecutiveFailures int       `json:"consecutive_failures"`
	Rev                 int64     `json:"rev"`
	CreatedAt           time.Time `json:"created_at"`
}

// WebhookSecret is the only view of a signing secret, returned by CreateWebhook.
type WebhookSecret struct {
	Webhook
	Secret string `json:"secret"`
}

// WebhookInput is the create payload; the secret is generated by the server.
type WebhookInput struct {
	URL    string
	Events []string
}

// WebhookPatch applies a partial update; nil fields keep their current value.
// Events must be nil or a complete replacement set.
type WebhookPatch struct {
	URL    *string
	Events []string
	Active *bool
}

const (
	webhookSecretPrefix  = "whsec_"
	webhookSecretPurpose = "earnest/webhook-secrets/v1"
	webhookSecretBytes   = 32
)

// newWebhookSecret issues a Standard Webhooks secret shown once, then stored
// encrypted. The whsec_-prefixed base64 form matches the specification.
func newWebhookSecret() (string, error) {
	raw := make([]byte, webhookSecretBytes)
	if _, err := rand.Read(raw); err != nil {
		return "", fmt.Errorf("generate webhook secret: %w", err)
	}
	return webhookSecretPrefix + base64.StdEncoding.EncodeToString(raw), nil
}

// decodeWebhookSecret recovers the raw HMAC key from its stored form.
func decodeWebhookSecret(secret string) ([]byte, error) {
	encoded, ok := strings.CutPrefix(secret, webhookSecretPrefix)
	if !ok {
		return nil, fmt.Errorf("webhook secret prefix: %w", ErrInvalid)
	}
	raw, err := base64.StdEncoding.DecodeString(encoded)
	if err != nil || len(raw) < 16 {
		return nil, fmt.Errorf("webhook secret encoding: %w", ErrInvalid)
	}
	return raw, nil
}

// sealWebhookSecret encrypts a signing secret for storage, using the service's
// credential envelope with a webhook-specific authenticated purpose.
func (s *Service) sealWebhookSecret(secret string) ([]byte, error) {
	nonce := make([]byte, s.credentials.NonceSize())
	if _, err := rand.Read(nonce); err != nil {
		return nil, fmt.Errorf("webhook secret nonce: %w", err)
	}
	return s.credentials.Seal(nonce, nonce, []byte(secret), []byte(webhookSecretPurpose)), nil
}

// openWebhookSecret reverses sealWebhookSecret for a delivery attempt.
func (s *Service) openWebhookSecret(body []byte) (string, error) {
	if len(body) == 0 {
		return "", fmt.Errorf("webhook secret envelope: %w", ErrInvalid)
	}
	n := s.credentials.NonceSize()
	if len(body) < n {
		return "", fmt.Errorf("webhook secret envelope: %w", ErrInvalid)
	}
	plain, err := s.credentials.Open(nil, body[:n], body[n:], []byte(webhookSecretPurpose))
	if err != nil {
		return "", fmt.Errorf("decrypt webhook secret: %w", ErrUnavailable)
	}
	return string(plain), nil
}

// signWebhook signs one message per the Standard Webhooks scheme: the signed
// content is id.timestamp.body under HMAC-SHA256 keyed by the decoded secret,
// returned as the webhook-signature header value "v1,<base64>".
func signWebhook(secret, messageID string, timestamp int64, body []byte) (string, error) {
	key, err := decodeWebhookSecret(secret)
	if err != nil {
		return "", err
	}
	mac := hmac.New(sha256.New, key)
	mac.Write([]byte(messageID + "." + strconv.FormatInt(timestamp, 10) + "."))
	mac.Write(body)
	return "v1," + base64.StdEncoding.EncodeToString(mac.Sum(nil)), nil
}

func validWebhookEvents(events []string) bool {
	if len(events) == 0 {
		return false
	}
	seen := map[string]bool{}
	for _, event := range events {
		switch WebhookEventType(event) {
		case WebhookFeedFailing, WebhookEditionReady, WebhookEntryMatched:
		default:
			return false
		}
		if seen[event] {
			return false
		}
		seen[event] = true
	}
	return true
}

// checkWebhookOwner enforces the human-only webhooks:write policy on every
// surface; the schema's human_webhook trigger backs it at the row level.
func (s *Service) checkWebhookOwner(ctx context.Context, a Actor) error {
	if err := s.checkActor(ctx, a, ScopeWebhooksWrite); err != nil {
		return err
	}
	if a.Kind != PrincipalHuman {
		return ErrForbidden
	}
	return nil
}

// Webhooks lists the user's destinations in stable ID order.
func (s *Service) Webhooks(ctx context.Context, a Actor) ([]Webhook, error) {
	if err := s.checkWebhookOwner(ctx, a); err != nil {
		return nil, err
	}
	rows, err := s.store.Pool().Query(ctx, `SELECT id,url,events,active,consecutive_failures,rev,created_at
  FROM webhooks WHERE user_id=$1 ORDER BY id`, a.UserID)
	if err != nil {
		return nil, fmt.Errorf("list webhooks: %w", err)
	}
	defer rows.Close()
	out := []Webhook{}
	for rows.Next() {
		var w Webhook
		if err := rows.Scan(&w.ID, &w.URL, &w.Events, &w.Active, &w.ConsecutiveFailures, &w.Rev, &w.CreatedAt); err != nil {
			return nil, err
		}
		out = append(out, w)
	}
	return out, rows.Err()
}

// CreateWebhook registers a destination and issues its signing secret once.
// A replayed op_id returns the created webhook without the secret.
func (s *Service) CreateWebhook(ctx context.Context, a Actor, in WebhookInput, opID string) (WebhookSecret, error) {
	if err := s.checkWebhookOwner(ctx, a); err != nil {
		return WebhookSecret{}, err
	}
	if !validOpID(opID) || !feedURLValid(in.URL) || !validWebhookEvents(in.Events) {
		return WebhookSecret{}, ErrInvalid
	}
	secret, err := newWebhookSecret()
	if err != nil {
		return WebhookSecret{}, err
	}
	sealed, err := s.sealWebhookSecret(secret)
	if err != nil {
		return WebhookSecret{}, err
	}
	out := WebhookSecret{Secret: secret}
	err = s.store.WithTx(ctx, func(tx pgx.Tx) error {
		if err := store.LockCore(ctx, tx); err != nil {
			return err
		}
		replay, err := replayOp(ctx, tx, a.PrincipalID, "CreateWebhook", opID)
		if err != nil {
			return err
		}
		if replay != nil {
			out.Secret = ""
			return json.Unmarshal(replay, &out.Webhook)
		}
		err = tx.QueryRow(ctx, `INSERT INTO webhooks(user_id,created_by,url,secret_encrypted,events,rev)
   VALUES($1,$2,$3,$4,$5,1) RETURNING id,created_at`,
			a.UserID, a.PrincipalID, in.URL, sealed, in.Events).Scan(&out.ID, &out.CreatedAt)
		if err != nil {
			return domainError(err)
		}
		out.URL, out.Events, out.Active, out.Rev = in.URL, slices.Clone(in.Events), true, 1
		return store.FinishOp(ctx, tx, a.PrincipalID, opID, out.Webhook)
	})
	if err != nil {
		return WebhookSecret{}, domainError(err)
	}
	return out, nil
}

// UpdateWebhook applies a partial patch. Re-enabling a disabled destination
// resets its consecutive failure count.
func (s *Service) UpdateWebhook(ctx context.Context, a Actor, id int64, patch WebhookPatch, opID string) (Webhook, error) {
	if err := s.checkWebhookOwner(ctx, a); err != nil {
		return Webhook{}, err
	}
	if id <= 0 || !validOpID(opID) || (patch.URL == nil && patch.Events == nil && patch.Active == nil) {
		return Webhook{}, ErrInvalid
	}
	if patch.URL != nil && !feedURLValid(*patch.URL) {
		return Webhook{}, fmt.Errorf("url: %w", ErrInvalid)
	}
	if patch.Events != nil && !validWebhookEvents(patch.Events) {
		return Webhook{}, fmt.Errorf("events: %w", ErrInvalid)
	}
	var out Webhook
	err := s.store.WithTx(ctx, func(tx pgx.Tx) error {
		if err := store.LockCore(ctx, tx); err != nil {
			return err
		}
		replay, err := replayOp(ctx, tx, a.PrincipalID, "UpdateWebhook", opID)
		if err != nil {
			return err
		}
		if replay != nil {
			return json.Unmarshal(replay, &out)
		}
		var url string
		if err := tx.QueryRow(ctx, "SELECT url,events,active FROM webhooks WHERE user_id=$1 AND id=$2 FOR UPDATE", a.UserID, id).Scan(&url, &out.Events, &out.Active); err != nil {
			return domainError(err)
		}
		events, active := out.Events, out.Active
		if patch.URL != nil {
			url = *patch.URL
		}
		if patch.Events != nil {
			events = patch.Events
		}
		if patch.Active != nil {
			active = *patch.Active
		}
		if err := tx.QueryRow(ctx, `UPDATE webhooks SET url=$3,events=$4,active=$5,rev=rev+1,
   consecutive_failures=CASE WHEN $5 AND NOT active THEN 0 ELSE consecutive_failures END
   WHERE id=$1 AND user_id=$2 RETURNING consecutive_failures,rev,created_at`,
			id, a.UserID, url, events, active).Scan(&out.ConsecutiveFailures, &out.Rev, &out.CreatedAt); err != nil {
			return domainError(err)
		}
		out.ID, out.URL, out.Events, out.Active = id, url, slices.Clone(events), active
		return store.FinishOp(ctx, tx, a.PrincipalID, opID, out)
	})
	if err != nil {
		return Webhook{}, domainError(err)
	}
	return out, nil
}

// DeleteWebhook removes a destination and discards its pending deliveries.
func (s *Service) DeleteWebhook(ctx context.Context, a Actor, id int64, opID string) error {
	if err := s.checkWebhookOwner(ctx, a); err != nil {
		return err
	}
	if id <= 0 || !validOpID(opID) {
		return ErrInvalid
	}
	out := Webhook{ID: id}
	err := s.store.WithTx(ctx, func(tx pgx.Tx) error {
		if err := store.LockCore(ctx, tx); err != nil {
			return err
		}
		replay, err := replayOp(ctx, tx, a.PrincipalID, "DeleteWebhook", opID)
		if err != nil {
			return err
		}
		if replay != nil {
			return nil
		}
		if err := tx.QueryRow(ctx, "DELETE FROM webhooks WHERE user_id=$1 AND id=$2 RETURNING url,events,active,rev,created_at",
			a.UserID, id).Scan(&out.URL, &out.Events, &out.Active, &out.Rev, &out.CreatedAt); err != nil {
			return domainError(err)
		}
		if _, err := tx.Exec(ctx, "DELETE FROM jobs WHERE kind='webhook' AND (payload->>'webhook_id')::bigint=$1", id); err != nil {
			return fmt.Errorf("discard webhook jobs: %w", err)
		}
		return store.FinishOp(ctx, tx, a.PrincipalID, opID, out)
	})
	return domainError(err)
}
